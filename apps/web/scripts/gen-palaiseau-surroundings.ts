/**
 * Generates src/demo/palaiseauSurroundings.ts from the recorded raw Palaiseau fixtures
 * (apps/server/test/fixtures/palaiseau/raw; trees from the synthetic overpass-green.json), mapped
 * with the server's layer mapping and converted with toSurroundings into the demo's local frame.
 * Coordinates are rounded to 0.01 m. The web bundle never imports the raw fixtures.
 *
 *   pnpm --filter @kubatur/server exec tsx ../web/scripts/gen-palaiseau-surroundings.ts
 * (The output is listed in .prettierignore to stay compact.)
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { createProject } from '@kubatur/core';
import { mapCadastreFeatures } from '../../server/src/geo/apicarto.js';
import {
  mapBdTopoGreen,
  mapBdTopoRoads,
  mapBdTopoWater,
  mapOsmLayers,
} from '../../server/src/geo/layers.js';
import type { ContextLayersResponse, LonLat } from '../src/api/contract';
import { toSurroundings } from '../src/geo/context';

const FIX = join(import.meta.dirname, '../../server/test/fixtures');
const read = (p: string) => JSON.parse(readFileSync(join(FIX, p), 'utf8')) as unknown;
const raw = (f: string) => read(`palaiseau/raw/${f}`);

// Same site as src/demo/palaiseau.ts
const parcel = read('palaiseau/parcel-0518.json') as {
  features: { properties: { idu: string }; geometry: { coordinates: number[][][][] } }[];
};
const f = parcel.features[0]!;
const project = createProject({
  name: 'demo',
  parcelsLonLat: [
    { ref: f.properties.idu, rings: f.geometry.coordinates[0]!.map((r) => r as LonLat[]) },
  ],
});

const streets = mapOsmLayers(raw('overpass-streets.json'));
const green = mapOsmLayers(read('synthetic/overpass-green.json'));
const ignGreen = [
  ...mapBdTopoGreen(raw('bdtopo-zone_de_vegetation.json')),
  ...mapBdTopoGreen(raw('bdtopo-haie.json'), 'hedge'),
];
const res: ContextLayersResponse = {
  roads: [
    ...mapBdTopoRoads(raw('bdtopo-troncon_de_route.json'), { dropTrails: true }),
    ...streets.roads.filter((r) =>
      ['footway', 'cycleway', 'path', 'rail', 'tram'].includes(r.kind),
    ),
  ],
  green: [...ignGreen, ...green.green],
  trees: green.trees,
  water: [...mapBdTopoWater(raw('bdtopo-surface_hydrographique.json')), ...streets.water],
  parcels: mapCadastreFeatures(raw('apicarto-parcelles-bbox.json')),
  providers: {},
};
const s = toSurroundings(
  res,
  project.geo,
  project.site.parcels.flatMap((p) => p.ref ?? []),
);

const round = (_k: string, v: unknown) => (typeof v === 'number' ? Math.round(v * 100) / 100 : v);
const out =
  `// GENERATED by apps/web/scripts/gen-palaiseau-surroundings.ts – do not edit.\n` +
  `// Real IGN BD TOPO / API Carto / OSM data (raw fixtures, 2026-11-21); trees are SYNTHETIC.\n` +
  `import type { Surroundings } from '@kubatur/core';\n\n` +
  `export const palaiseauSurroundings: Surroundings = ${JSON.stringify(s, round)};\n`;
writeFileSync(join(import.meta.dirname, '../src/demo/palaiseauSurroundings.ts'), out);
console.log(
  `roads ${s.roads.length}, green ${s.green.length}, trees ${s.trees.length}, water ${s.water.length}, parcels ${s.parcels.length}, ${out.length} bytes`,
);
